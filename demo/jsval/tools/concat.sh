#!/bin/sh
# Build x3dval.js = banner + src/*.js in name order (no bundler; the result is committed so no build step is needed).
set -e
cd "$(dirname "$0")/.."
OUT=x3dval.js
{
  echo "/* x3dval.js -- js-port-of-8dd0d3e: browser/worker/Node port of the x3d_mcp fork validator (commit 8dd0d3e)."
  echo " * Generated by tools/concat.sh from src/*.js (do not edit; edit src/ and re-run). Not the fork itself."
  echo " * Engine: libxml2-wasm 0.7.2 (vendor/libxml2-wasm.bundle.mjs, loaded with dynamic import())."
  echo " */"
  for f in src/*.js; do
    echo ""
    echo "/* ===== $f ===== */"
    cat "$f"
  done
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes) from: $(ls src/*.js | tr '\n' ' ')"
